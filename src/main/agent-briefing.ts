/**
 * agent-briefing — generates per-agent CLAUDE.md briefings.
 *
 * Each code-terminal agent gets:
 *   ${rootDir}/.yo/agents/<name>.md    — terse role briefing + team context
 *
 * The project's top-level CLAUDE.md gets a managed dispatcher section
 * (between markers) that points the agent at its own briefing based on
 * the YO_AGENT_NAME env var. We only manage the section between the
 * markers; everything else in the user's CLAUDE.md is preserved.
 *
 * Delivery model: when the panel spawns `claude` with cwd=rootDir and
 * env.YO_AGENT_NAME=<name>, Claude Code reads the project CLAUDE.md at
 * startup, sees the dispatch instruction, and (per its own agency) reads
 * the per-agent briefing for full role context.
 */
import * as fs from "fs";
import * as path from "path";
import type { Workspace, CodeAgent } from "./workspace-manager";

const MANAGED_START = "<!-- YOSUP:MULTI-AGENT START — managed by yo-client, do not edit -->";
const MANAGED_END = "<!-- YOSUP:MULTI-AGENT END -->";

const MANAGED_BLOCK = `${MANAGED_START}
This is a yosup multi-agent workspace. If \`$YO_AGENT_NAME\` is set in your
environment, you are that named agent. Read \`.yo/agents/$YO_AGENT_NAME.md\`
for your role briefing and team coordination protocol.

When responding to user input, **first read your inbox** at
\`.yo/inbox/$YO_AGENT_NAME.md\` if it exists — it contains team updates
delivered since your last turn.
${MANAGED_END}`;

/** Render a per-agent briefing (terse, ~500 tokens). */
function renderAgentBriefing(workspace: Workspace, agent: CodeAgent, teammates: CodeAgent[]): string {
  const peers = teammates.filter((t) => t.name !== agent.name);
  const peerList = peers.length > 0
    ? peers.map((t) => `- \`${t.name}\` — role: ${t.role}`).join("\n")
    : "_(none yet — you may be working solo, or other agents will join later)_";

  return `# Agent: ${agent.name}

You are agent **${agent.name}** in workspace **${workspace.slug}** (cwd: \`${workspace.rootDir}\`).

- **Role:** ${agent.role}
- **Orchestrator:** \`yo\` (the .yo agent in this app)

## Teammates

${peerList}

## Coordination protocol

At the start of every turn, read \`.yo/inbox/${agent.name}.md\` if it
exists — events above the last-read timestamp are new since your last turn.

Workspace MCP tools (available once Phase 3 ships):
\`team_status\`, \`read_log\`, \`read_agent\`, \`post\`, \`post_to\`, \`subscribe\`.

**Sender conventions:**
- Status updates: \`post(body, tags: ["broadcast"])\`
- Cross-role asks: \`post_to("<other>", body)\` or \`post(body, tags: ["role:<other>"])\`
- Internal scratch: \`post(body)\` with no tags (stays in log, not delivered to peers)
- Use tag \`blocking\` for anything that requires a teammate response before you continue

The user is the final authority — defer to them on scope.

---

_This file is auto-generated by yo-client when the agent is created or the
roster changes. Edits will be overwritten._
`;
}

/** Write the per-agent briefing to ${rootDir}/.yo/agents/<name>.md */
export function writeAgentBriefing(workspace: Workspace, agent: CodeAgent, allAgents: CodeAgent[]): void {
  const dir = path.join(workspace.rootDir, ".yo", "agents");
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, `${agent.name}.md`);
  fs.writeFileSync(file, renderAgentBriefing(workspace, agent, allAgents));
}

/** Rewrite all agents' briefings — call when the roster changes so peer
 *  lists stay in sync. Cheap (a few small writes). */
export function rewriteAllBriefings(workspace: Workspace, agents: CodeAgent[]): void {
  for (const a of agents) writeAgentBriefing(workspace, a, agents);
}

/** Ensure ${rootDir}/CLAUDE.md has a managed multi-agent dispatcher section.
 *  Preserves all existing content; only adds/updates between markers. */
export function ensureProjectClaudeMd(workspace: Workspace): void {
  const file = path.join(workspace.rootDir, "CLAUDE.md");
  let body = "";
  if (fs.existsSync(file)) {
    body = fs.readFileSync(file, "utf-8");
  }

  if (body.includes(MANAGED_START) && body.includes(MANAGED_END)) {
    // Update in place
    const updated = body.replace(
      new RegExp(`${escapeRegex(MANAGED_START)}[\\s\\S]*?${escapeRegex(MANAGED_END)}`),
      MANAGED_BLOCK,
    );
    if (updated !== body) fs.writeFileSync(file, updated);
    return;
  }

  // Append managed block (separated by blank line)
  const sep = body.length === 0 ? "" : body.endsWith("\n\n") ? "" : body.endsWith("\n") ? "\n" : "\n\n";
  fs.writeFileSync(file, body + sep + MANAGED_BLOCK + "\n");
}

/** Remove the managed section from CLAUDE.md (e.g., when the last agent is
 *  deleted). Leaves user content intact. */
export function removeProjectClaudeMdManagedSection(workspace: Workspace): void {
  const file = path.join(workspace.rootDir, "CLAUDE.md");
  if (!fs.existsSync(file)) return;
  const body = fs.readFileSync(file, "utf-8");
  if (!body.includes(MANAGED_START)) return;
  const stripped = body.replace(
    new RegExp(`\\n*${escapeRegex(MANAGED_START)}[\\s\\S]*?${escapeRegex(MANAGED_END)}\\n*`),
    "\n",
  ).trimEnd() + "\n";
  fs.writeFileSync(file, stripped);
}

function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
